"""Build the exact float32-period timestamp converter, without shaderInt64."""
from pathlib import Path
from tool_paths import shader_tools
import random
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
TOOLS = shader_tools()
MASK32 = (1 << 32) - 1


def limb_convert(raw, bits, multiplier, shift, left):
    """Mirror the shader's uint operations for the small mathematical probe."""
    lo, hi = raw & MASK32, raw >> 32
    bits = min(bits, 64)
    if bits == 0:
        lo = hi = 0
    elif bits < 32:
        lo &= (1 << bits) - 1
        hi = 0
    elif bits == 32:
        hi = 0
    elif bits < 64:
        hi &= (1 << (bits - 32)) - 1
    low_product, high_product = lo * multiplier, hi * multiplier
    middle = ((high_product & MASK32) + (low_product >> 32)) & MASK32
    high = (high_product >> 32) + (middle < (high_product & MASK32))
    limbs = [low_product & MASK32, middle, high]

    def shift96(value, amount, to_left):
        if amount >= 96:
            return [0, 0, 0]
        whole, part = divmod(amount, 32)
        result = [0, 0, 0]
        for i in range(3):
            source = i - whole if to_left else i + whole
            if 0 <= source < 3:
                result[i] = ((value[source] << part) if to_left else (value[source] >> part)) & MASK32
                adjacent = source - 1 if to_left else source + 1
                if part and 0 <= adjacent < 3:
                    result[i] |= ((value[adjacent] >> (32 - part)) if to_left else (value[adjacent] << (32 - part))) & MASK32
        return result

    if left:
        limbs = shift96(limbs, shift, True)
    quotient, remainder = [0, 0, 0], 0
    for bit in range(95, -1, -1):
        word, subbit = divmod(bit, 32)
        next_bit = (limbs[word] >> subbit) & 1
        remainder = remainder * 2 + next_bit
        if remainder >= 625:
            remainder -= 625
            quotient[word] |= 1 << subbit
    if not left:
        quotient = shift96(quotient, shift, False)
    assert quotient[2] == 0
    return (quotient[1] << 32) | quotient[0]


def period_parameters(period):
    word = struct.unpack('<I', struct.pack('<f', period))[0]
    field, fraction = (word >> 23) & 255, word & 0x7fffff
    assert not word >> 31 and field != 255 and (field or fraction)
    mantissa = fraction | (0x800000 if field else 0)
    exponent = field - 150 if field else -149
    return mantissa * 12, abs(exponent), exponent > 0


def reference(raw, bits, multiplier, shift, left):
    value = (raw & ((1 << bits) - 1)) * multiplier
    return (value << shift) // 625 if left else value // (625 << shift)


def verify_math():
    values = [0, 1, 52, 53, 624, 625, 626, (1 << 32) - 1,
              1 << 32, (1 << 32) + 1, (1 << 63), (1 << 64) - 1]
    rng = random.Random(625)
    values += [rng.getrandbits(64) for _ in range(16)]
    checks = 0
    for period in (1.0, 52.083332, 83.333336, 0.5, 2.0**24, 2.0**55, 2.0**56, 2.0**69, 2.0**-149):
        params = period_parameters(period)
        for bits in (1, 8, 24, 32, 48, 64):
            if reference((1 << 64) - 1, bits, *params) >= 1 << 64:
                continue  # Production host must reject this combination too.
            for raw in values:
                expected = reference(raw, bits, *params)
                assert limb_convert(raw, bits, *params) == expected, (raw, bits, period)
                checks += 1
    print(f'Timestamp integer probe: {checks} cases passed')


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'android-host/apk-out'
    out.mkdir(parents=True, exist_ok=True)
    verify_math()
    product = out / 'timestamp.spv'
    subprocess.run([str(TOOLS / 'glslc.exe'), '--target-env=vulkan1.1', '-O',
                    str(ROOT / 'android-host/shaders/timestamp.comp'), '-o', str(product)], check=True)
    subprocess.run([str(TOOLS / 'spirv-val.exe'), '--target-env', 'vulkan1.1', str(product)], check=True)
    code = product.read_bytes()
    words = struct.unpack(f'<{len(code)//4}I', code)
    at = 5
    while at < len(words):
        count, opcode = words[at] >> 16, words[at] & 65535
        assert count and at + count <= len(words), 'Malformed SPIR-V'
        if opcode == 17:  # OpCapability: Float64=10, Int64=11.
            assert words[at + 1] not in (10, 11), 'Unexpected 64-bit shader arithmetic'
        at += count
    lines = ['/* Generated by build_timestamp.py. binding0=32B; push uint validBits,multiplier,shift,left (16B). */',
             'static const uint32_t timestamp_spv[]={']
    lines += [','.join(f'0x{x:08x}u' for x in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
    lines += ['};', '']
    (out / 'timestamp_spv.inc').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Timestamp SPIR-V: {len(code)} bytes, Vulkan 1.1 validated, no Int64/Float64')


if __name__ == '__main__':
    main()
