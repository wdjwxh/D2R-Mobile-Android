"""Build the Android compute catalog from validated SPIR-V and upstream ABI.

No guest image rewriting. Generated output lives in apk-out, not the upstream tree.
"""
import hashlib
import json
from pathlib import Path
from tool_paths import shader_tools
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import spv_build

def binding_sample_types(code, bindings):
    words=struct.unpack('<%dI'%(len(code)//4),code);types={};variables={};decorations={};at=5
    while at<len(words):
        n,op=words[at]>>16,words[at]&65535;p=words[at:at+n]
        if not n:raise ValueError('Invalid SPIR-V instruction')
        if op in (21,22,25,27,32):types[p[1]]=(op,p[2:])
        elif op==59:variables[p[2]]=p[1]
        elif op==71 and n==4 and p[2]==33:decorations[p[1]]=p[3]
        at+=n
    flags={}
    for variable,binding in decorations.items():
        typ=variables.get(variable)
        for _ in range(5):
            if typ not in types:break
            op,args=types[typ]
            if op==32:typ=args[1]
            elif op in (27,25):typ=args[0]
            elif op==21:flags[binding]=0x20000 if args[1] else 0x10000;break
            else:break
    return [(*b[:3],b[3]|flags.get(b[0],0),*b[4:]) for b in bindings]

def reflect_bindings(j):
    key=j['key'];binds=[(0,0,0,0,0)]
    for b in j['cbufs']:
        slot=b['slot'];kind=1 if slot>=3 else 5 if slot==1 else 4
        binds.append((b['binding'],kind,slot-3 if kind==1 else slot,0,0))
    for b in j['sbufs']:
        off=b['cb_offset']*4
        if b['cb_slot']!=0 or off%16: raise ValueError((key,'Unmapped storage ABI',b))
        base={'vs':0x110,'ps':0x510,'cs':0x310}[j['stage']]
        if j['stage']=='cs' and 0x210<=off<0x310: kind,slot=3,(off-0x210)//16
        elif base<=off<base+0x100: kind,slot=2,(off-base)//16
        else: raise ValueError((key,'Unmapped storage offset',b))
        binds.append((b['binding'],kind,slot,b['flags'],0))
    for kind,group,base in ((6,'textures',0x168),(7,'images',0x120)):
        for b in j[group]:
            # Upstream decode_tex searches BOTH packed words: their ordering
            # may be sampler then texture, not always texture then sampler.
            packed=b['handle'];banks=b['cbuf_slot']
            texture_bank=(banks&65535) if banks>=0 else 2
            sampler_bank=((banks>>16)-1) if banks>=0 and banks>>16 else texture_bank
            words=[packed&0x3fff]+([(packed>>14)&0x3fff] if packed>>28 else [])
            limit=0x568 if kind==6 else 0x168
            slot=next(((word*4-base)//8 for word in words if texture_bank==2 and base<=word*4<limit and (word*4-base)%8==0),-1)
            sampler_slot=next(((word*4-0x568)//8 for word in words if sampler_bank==2 and 0x568<=word*4<0x968 and (word*4-0x568)%8==0),-1) if packed>>28 else -1
            if slot<0 or (packed>>28 and kind==6 and sampler_slot<0): raise ValueError((key,'Unmapped texture/sampler ABI',b))
            if b['array']!=1 or b['separate']: raise ValueError((key,'Descriptor array/separate image needs dedicated ABI',b))
            binds.append((b['binding'],kind,slot,b['flags'],b['type'],sampler_slot))
    return [b if len(b)==6 else (*b,-1) for b in binds]


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    tools = shader_tools()
    parts = ['/* Generated by build_compute.py; upstream control keys, Android SPIR-V. */']
    rows = []

    def array(name, data, words=False):
        values = struct.unpack('<%dI' % (len(data)//4), data) if words else data
        parts.append(f'static const {"uint32_t" if words else "uint8_t"} {name}[]={{')
        for i in range(0, len(values), 12):
            parts.append(','.join(hex(x) for x in values[i:i+12])+',')
        if not values: parts.append('0,')
        parts.append('};')

    def add(key, data, binds, constants, builtin):
        binds=binding_sample_types(data,binds)
        words=struct.unpack('<%dI' % (len(data)//4),data)
        local=None
        pos=5
        while pos<len(words):
            count,op=words[pos]>>16,words[pos]&65535
            if not count: raise ValueError('Invalid SPIR-V instruction')
            if op==16 and words[pos+2]==17: local=words[pos+3:pos+6]
            pos+=count
        if not local: raise ValueError('Missing fixed compute local size: '+key)
        name='cs_'+key
        array(name,data,True);array(name+'_c1',constants)
        parts.append('static const dm_shader_binding '+name+'_b[]={'+','.join('{'+','.join(map(str,b if len(b)==6 else (*b,-1)))+'}' for b in binds)+'};')
        rows.append('{"%s",%s,sizeof %s,%s_b,%d,%s_c1,%d,{%s},%d}' %
                    (key,name,name,name,len(binds),name,len(constants),','.join(map(str,local)),builtin))

    builtin_keys=('d0f769bb916bbba9','16479cc6d75c2b28','0687e2ef95133577','4df5909e6dabee05')
    for i,key in enumerate(builtin_keys):
        product=out/f'counter{i}.spv'
        subprocess.run([str(tools/'glslc.exe'),'--target-env=vulkan1.1','-O',f'-DKERNEL={i}',
                        str(ROOT/'android-host/shaders/counter.comp'),'-o',str(product)],check=True)
        subprocess.run([str(tools/'spirv-val.exe'),'--target-env','vulkan1.1',str(product)],check=True)
        add(key,product.read_bytes(),[(0,8,0,0,0),(1,2,0,0,0),(2,2,1,1,0)],b'',i)

    shader_dir=ROOT/'android-work/shaders/spv-adreno'
    loc,_,_=spv_build.load_map(str(ROOT/'d2r-mobile/dm/gfx/nvn'))
    packs={}
    for reflection in sorted(shader_dir.glob('*.res.json')):
        j=json.loads(reflection.read_text(encoding='utf-8'))
        if j['stage']!='cs': continue
        key=j['key'];binds=reflect_bindings(j)
        name,index=loc[key]
        if name not in packs: packs[name]=spv_build.records((ROOT/'android-work/shaders/packs'/Path(name).name).read_bytes())
        record=packs[name][index];control=record.index(spv_build.CTRL)
        assert hashlib.sha256(record[control:control+0x880]).hexdigest()[:16]==key
        start,end=struct.unpack_from('<II',record,control+0x700)
        constants=record[0x38+start:0x38+end]
        product=shader_dir/(key+'.spv')
        subprocess.run([str(tools/'spirv-val.exe'),'--target-env','vulkan1.1',str(product)],check=True)
        add(key,product.read_bytes(),binds,constants,-1)
    parts.append('static const dm_compute_shader compute_catalog[]={'+',\n'.join(rows)+'};')
    (out/'compute_catalog.inc').write_text('\n'.join(parts)+'\n',encoding='utf-8')
    print('Compute catalog:',len(rows),'kernels (4 builtin + 22 packaged)')

if __name__=='__main__': main()
